//! Merging what `init-repo` generates into files that may already hold the user's own
//! settings. Every function returns the full new text, or the reason the file is left alone.
use serde_json::{Map, Value, json};

/// One change to a JSON settings file.
pub(super) enum Op {
    /// Replaces the value at an object path, creating the objects on the way.
    Set(&'static [&'static str], Value),
    /// Sets a top-level key only when it is missing.
    SetIfAbsent(&'static str, Value),
    /// Replaces our entries in `hooks.<event>` (in place), keeping every other entry. An empty
    /// list removes ours and leaves the event out once nothing else is in it.
    Hooks(&'static str, Vec<Value>),
    /// Replaces the `inputs` entry with the same `id`, or appends it.
    Input(Value),
}

/// Text owned by us between two marker lines.
pub(super) struct Block {
    /// The start of the begin line, which identifies it whatever follows.
    pub(super) begin_prefix: &'static str,
    pub(super) begin: &'static str,
    pub(super) end: &'static str,
}

pub(super) const MARKDOWN: Block = Block {
    begin_prefix: "<!-- agentscm:begin",
    begin: "<!-- agentscm:begin -->",
    end: "<!-- agentscm:end -->",
};

pub(super) const TOML: Block = Block {
    begin_prefix: "# agentscm:begin",
    begin: "# agentscm:begin (generated by agentscm init-repo; edits inside this block are replaced)",
    end: "# agentscm:end",
};

fn is_ours(value: &Value) -> bool {
    value["url"]
        .as_str()
        .is_some_and(|u| u.contains("/v1/hub/hook/"))
        || value["command"]
            .as_str()
            .is_some_and(|c| c.starts_with("agentscm hook "))
}

/// Swaps our entries for `new` at the place of the first of them; a group that also holds
/// the user's hooks stays, minus ours.
fn replace_ours(list: &mut Vec<Value>, new: &[Value]) {
    let mut out = Vec::new();
    let mut at = None;
    for mut entry in std::mem::take(list) {
        if is_ours(&entry) {
            at.get_or_insert(out.len());
            continue;
        }
        let mut stripped = false;
        let mut emptied = false;
        if let Some(inner) = entry.get_mut("hooks").and_then(Value::as_array_mut) {
            let before = inner.len();
            inner.retain(|hook| !is_ours(hook));
            stripped = inner.len() != before;
            emptied = stripped && inner.is_empty();
        }
        if stripped {
            at.get_or_insert(out.len() + usize::from(!emptied));
        }
        if !emptied {
            out.push(entry);
        }
    }
    let at = at.unwrap_or(out.len());
    out.splice(at..at, new.iter().cloned());
    *list = out;
}

fn object<'a>(parent: &'a mut Map<String, Value>, key: &str) -> &'a mut Value {
    parent.entry(key).or_insert_with(|| json!({}))
}

fn apply(root: &mut Map<String, Value>, op: &Op) -> Result<(), String> {
    match op {
        Op::Set(path, value) => {
            let (last, parents) = path.split_last().ok_or("empty path")?;
            let mut at = &mut *root;
            for key in parents {
                at = object(at, key)
                    .as_object_mut()
                    .ok_or_else(|| format!("\"{key}\" is not a JSON object"))?;
            }
            at.insert((*last).to_owned(), value.clone());
        }
        Op::SetIfAbsent(key, value) => {
            root.entry(*key).or_insert_with(|| value.clone());
        }
        Op::Hooks(event, new) => {
            let hooks = object(root, "hooks")
                .as_object_mut()
                .ok_or("\"hooks\" is not a JSON object")?;
            // An empty `new` only removes our entries; it never creates the event.
            if new.is_empty() && !hooks.contains_key(*event) {
                return Ok(());
            }
            let list = hooks.entry(*event).or_insert_with(|| json!([]));
            let list = list
                .as_array_mut()
                .ok_or_else(|| format!("\"hooks.{event}\" is not a JSON array"))?;
            replace_ours(list, new);
            if new.is_empty() && list.is_empty() {
                hooks.remove(*event);
            }
        }
        Op::Input(input) => {
            let list = root.entry("inputs").or_insert_with(|| json!([]));
            let list = list
                .as_array_mut()
                .ok_or("\"inputs\" is not a JSON array")?;
            match list.iter().position(|i| i["id"] == input["id"]) {
                Some(at) => list[at] = input.clone(),
                None => list.push(input.clone()),
            }
        }
    }
    Ok(())
}

pub(super) fn json_file(existing: Option<&str>, ops: &[Op]) -> Result<String, String> {
    let mut root = match existing.filter(|text| !text.trim().is_empty()) {
        None => Value::Object(Map::new()),
        Some(text) => serde_json::from_str(text)
            .map_err(|_| "it is not valid JSON (comments are not supported)".to_owned())?,
    };
    let root = root.as_object_mut().ok_or("it is not a JSON object")?;
    for op in ops {
        apply(root, op)?;
    }
    let mut text = serde_json::to_string_pretty(root).map_err(|e| e.to_string())?;
    text.push('\n');
    Ok(text)
}

/// Puts `body` between the block's markers: replacing the block when present, else
/// appending it.
pub(super) fn block_file(
    existing: Option<&str>,
    block: &Block,
    body: &str,
) -> Result<String, String> {
    let text = existing.unwrap_or_default();
    let new = format!("{}\n{}\n{}\n", block.begin, body.trim_end(), block.end);
    let lines: Vec<&str> = text.split_inclusive('\n').collect();
    let begin = lines
        .iter()
        .position(|l| l.trim().starts_with(block.begin_prefix));
    let end = lines.iter().position(|l| l.trim() == block.end);
    match (begin, end) {
        (Some(b), Some(e)) if b < e => Ok(format!(
            "{}{new}{}",
            lines[..b].concat(),
            lines[e + 1..].concat()
        )),
        (None, None) => {
            let mut out = text.to_owned();
            if !out.is_empty() && !out.ends_with('\n') {
                out.push('\n');
            }
            if !out.is_empty() {
                out.push('\n');
            }
            Ok(out + &new)
        }
        _ => Err("its agentscm markers are unbalanced".into()),
    }
}

/// Ensures the file has `line` (an `@AGENTS.md` import), creating it if needed.
pub(super) fn import_file(existing: Option<&str>, line: &str) -> String {
    let text = existing.unwrap_or_default();
    if text.lines().any(|l| l.trim() == line) {
        return text.to_owned();
    }
    let mut out = text.to_owned();
    if !out.is_empty() && !out.ends_with('\n') {
        out.push('\n');
    }
    out + line + "\n"
}

/// Whether TOML text, apart from our block, already defines the agentscm MCP server.
pub(super) fn toml_defines_server(text: &str) -> bool {
    let mut inside = false;
    for line in text.lines() {
        let line = line.trim();
        if line.starts_with(TOML.begin_prefix) {
            inside = true;
        } else if line == TOML.end {
            inside = false;
        } else if !inside && line.starts_with("[mcp_servers.agentscm") {
            return true;
        }
    }
    false
}

#[cfg(test)]
mod tests {
    use super::*;

    fn ours(url: &str) -> Value {
        json!({"type": "http", "url": url})
    }

    fn hooks_op(entries: Vec<Value>) -> Op {
        Op::Hooks("PreToolUse", entries)
    }

    #[test]
    fn hooks_update_in_place_and_keep_user_hooks() {
        let first = json_file(
            Some(
                r#"{"hooks":{"PreToolUse":[{"hooks":[{"type":"command","command":"mine"}]}]},"model":"x"}"#,
            ),
            &[hooks_op(vec![ours("https://a.test/v1/hub/hook/claude")])],
        )
        .unwrap();
        let second = json_file(
            Some(&first),
            &[hooks_op(vec![ours("https://b.test/v1/hub/hook/claude")])],
        )
        .unwrap();
        let value: Value = serde_json::from_str(&second).unwrap();
        assert_eq!(value["model"], "x");
        assert_eq!(
            value["hooks"]["PreToolUse"],
            json!([
                {"hooks": [{"type": "command", "command": "mine"}]},
                ours("https://b.test/v1/hub/hook/claude")
            ])
        );
    }

    #[test]
    fn a_group_mixing_ours_and_the_users_keeps_the_users() {
        let mixed = r#"{"hooks":{"PreToolUse":[{"matcher":"Bash","hooks":[
            {"type":"command","command":"mine"},
            {"type":"command","command":"agentscm hook codex --hub-url https://a.test"}]}]}}"#;
        let new = json!({"hooks": [{"type": "command", "command": "agentscm hook codex --hub-url https://b.test"}]});
        let out = json_file(Some(mixed), &[hooks_op(vec![new.clone()])]).unwrap();
        let value: Value = serde_json::from_str(&out).unwrap();
        assert_eq!(
            value["hooks"]["PreToolUse"],
            json!([
                {"matcher": "Bash", "hooks": [{"type": "command", "command": "mine"}]},
                new
            ])
        );
    }

    #[test]
    fn inputs_replace_by_id() {
        let input = json!({"id": "agentscm-token", "description": "new"});
        let out = json_file(
            Some(r#"{"inputs":[{"id":"other"},{"id":"agentscm-token","description":"old"}]}"#),
            &[Op::Input(input.clone())],
        )
        .unwrap();
        let value: Value = serde_json::from_str(&out).unwrap();
        assert_eq!(value["inputs"], json!([{"id": "other"}, input]));
    }

    #[test]
    fn bad_json_and_wrong_shapes_are_refused() {
        let ops = [Op::Set(&["mcpServers", "agentscm"], json!({}))];
        assert!(json_file(Some("{not json"), &ops).is_err());
        assert!(json_file(Some("[]"), &ops).is_err());
        assert!(json_file(Some(r#"{"mcpServers":[]}"#), &ops).is_err());
        assert!(json_file(Some(r#"{"hooks":{"PreToolUse":{}}}"#), &[hooks_op(vec![])]).is_err());
    }

    #[test]
    fn blocks_are_replaced_not_duplicated() {
        let once = block_file(Some("# Mine\n"), &MARKDOWN, "one").unwrap();
        assert_eq!(
            once,
            "# Mine\n\n<!-- agentscm:begin -->\none\n<!-- agentscm:end -->\n"
        );
        let twice = block_file(Some(&format!("{once}\nafter\n")), &MARKDOWN, "two").unwrap();
        assert_eq!(
            twice,
            "# Mine\n\n<!-- agentscm:begin -->\ntwo\n<!-- agentscm:end -->\n\nafter\n"
        );
        assert!(block_file(Some("<!-- agentscm:begin -->\n"), &MARKDOWN, "x").is_err());
    }

    #[test]
    fn import_line_is_added_once() {
        assert_eq!(import_file(None, "@AGENTS.md"), "@AGENTS.md\n");
        assert_eq!(import_file(Some("hi"), "@AGENTS.md"), "hi\n@AGENTS.md\n");
        assert_eq!(
            import_file(Some("a\n@AGENTS.md\n"), "@AGENTS.md"),
            "a\n@AGENTS.md\n"
        );
    }

    #[test]
    fn a_server_outside_the_block_is_found() {
        assert!(toml_defines_server("[mcp_servers.agentscm]\nurl = \"x\"\n"));
        let ours = format!("{}\n[mcp_servers.agentscm]\n{}\n", TOML.begin, TOML.end);
        assert!(!toml_defines_server(&ours));
    }
}
