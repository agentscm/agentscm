//! Compile-time verifier materials. Keep entries sorted by destination.

pub(super) struct Material {
    pub(super) destination: &'static str,
    pub(super) bytes: &'static [u8],
}

macro_rules! material {
    ($source:literal) => {
        Material {
            destination: concat!("verifier/", $source),
            bytes: include_bytes!(concat!("../tools/portable-verifier/", $source)),
        }
    };
}

