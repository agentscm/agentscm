test('requires an explicit discard before leaving a dirty workflow', async ({ page }) => {
  const state = await installWorkflowLibraryMock(page)
  state.workflows.push({ draft: { id: 'workflow-dirty', name: 'Protected draft', summary: 'Keep this work', generation: 1, steps: [], trigger: null, follow_on: null, updated_at: 1_798_000_000, archived: false }, versions: [] })
  await page.addInitScript((token) => localStorage.setItem('agentscm.token', token), LOCAL_TOKEN)
  await page.goto('/#templates?view=workflows')
  const main = page.locator('#main')
  await main.getByRole('button', { name: /Protected draft/ }).click()
  await main.getByLabel('Name').fill('Unsaved protected draft')
  await main.getByRole('button', { name: 'Workflow library' }).click()
  const discard = main.getByRole('group', { name: 'Discard unsaved workflow edits?' })
  await expect(discard).toBeVisible()
  await discard.getByRole('button', { name: 'Keep editing' }).click()
  await expect(main.getByLabel('Name')).toHaveValue('Unsaved protected draft')

  page.once('dialog', async (dialog) => {
    expect(dialog.message()).toBe('Discard unsaved workflow edits?')
    await dialog.dismiss()
  })
  await page.evaluate(() => { window.location.hash = 'templates?view=skills' })
  await expect(page).toHaveURL(/#templates\?view=workflows$/)
  await expect(main.getByLabel('Name')).toHaveValue('Unsaved protected draft')

  let crossSectionDialogs = 0
  page.once('dialog', async (dialog) => {
    crossSectionDialogs += 1
    expect(dialog.message()).toBe('Discard unsaved workflow edits?')
    await dialog.dismiss()
  })
  await page.evaluate(() => { window.location.hash = 'now' })
  await expect(page).toHaveURL(/#templates\?view=workflows$/)
  await expect(main.getByLabel('Name')).toHaveValue('Unsaved protected draft')
  expect(crossSectionDialogs).toBe(1)

  await page.getByRole('button', { name: /acme\/widgets on Test Mac/ }).click()
  page.once('dialog', async (dialog) => {
    expect(dialog.message()).toBe('Discard unsaved workflow edits?')
    await dialog.dismiss()
  })
  await page.getByRole('menuitemradio', { name: /beta\/gadgets/ }).click()
  await expect(main.getByLabel('Name')).toHaveValue('Unsaved protected draft')
  expect(await page.evaluate(() => localStorage.getItem('agentscm.token'))).toBe(LOCAL_TOKEN)

  await page.getByRole('button', { name: /acme\/widgets on Test Mac/ }).click()
  page.once('dialog', async (dialog) => {
    expect(dialog.message()).toBe('Discard unsaved workflow edits?')
    await dialog.dismiss()
  })
  await page.getByRole('menuitem', { name: /Disconnect this browser/ }).click()
  await expect(main.getByLabel('Name')).toHaveValue('Unsaved protected draft')
  expect(await page.evaluate(() => localStorage.getItem('agentscm.token'))).toBe(LOCAL_TOKEN)

  await main.getByRole('button', { name: 'Workflow library' }).click()
  await discard.getByRole('button', { name: 'Discard edits' }).click()
  await expect(main.getByText('Protected draft', { exact: true })).toBeVisible()
  expect(state.workflows[0]!.draft['name']).toBe('Protected draft')
})
