import { expect, test } from '@playwright/test'
import { installWorkflowLibraryMock, LOCAL_TOKEN } from './workflowLibraryMock.ts'

test('creates an exact skill and a versioned workflow, then simulates and attaches it', async ({ page }, testInfo) => {
  const state = await installWorkflowLibraryMock(page)
  state.workflows.push({
    draft: { id: 'workflow-seed', name: 'Release evidence', summary: 'Prepare the reusable release evidence package.', generation: 1, steps: [], trigger: null, follow_on: null, updated_at: 1_798_000_000, archived: false },
    versions: [{ id: 'workflow-seed-v1', workflow_id: 'workflow-seed', version: 1, digest: 'b'.repeat(64), definition: { id: 'workflow-seed', name: 'Release evidence', summary: 'Prepare the reusable release evidence package.', generation: 1, steps: [], trigger: null, follow_on: null, updated_at: 1_798_000_000, archived: false }, skill_versions: [], created_at: 1_798_000_000, archived: false }],
  })
  await page.addInitScript((token) => localStorage.setItem('agentscm.token', token), LOCAL_TOKEN)
  await page.goto('/#templates?view=skills')
  const main = page.locator('#main')
  await expect(main.getByRole('heading', { name: 'Which reusable workflows can agents configure here?' })).toBeVisible()

  await main.getByRole('button', { name: 'Add skill' }).click()
  await main.getByLabel('Skill name').fill('Release helper')
  await main.getByLabel('SKILL.md').fill('---\nname: release-helper\n---\n\n# Release helper\nPrepare exact release evidence.')
  await main.getByRole('button', { name: 'Preview exact files' }).click()
  await expect(main.getByText('1 file')).toBeVisible()
  await main.getByRole('button', { name: 'Save this exact skill version' }).click()
  await expect(main.locator('strong').filter({ hasText: 'Release helper' })).toBeVisible()
  await main.getByRole('button', { name: 'Add skill' }).click()
  await main.getByRole('button', { name: 'Preview exact files' }).click()
  await main.getByRole('button', { name: 'Save this exact skill version' }).click()
  await expect(main.locator('.wl-row').filter({ hasText: 'Release helper' })).toHaveCount(1)

  await main.getByRole('tab', { name: 'Workflows' }).click()
  await main.getByRole('button', { name: 'New workflow' }).click()
  await main.getByLabel('Name').fill('Major feature follow-up')
  await main.getByLabel('Purpose').fill('Prepare build evidence and a release action after a confirmed merge.')
  await main.getByRole('button', { name: 'Create', exact: true }).click()
  await main.getByRole('button', { name: 'Build', exact: true }).click()
  await main.getByLabel('Runner file').fill('runners/build.json')
  await main.getByRole('button', { name: 'Action', exact: true }).click()
  await main.getByLabel('Action resource').fill('actions/release-note.json')
  await main.getByLabel('Step ID').first().fill('compile')
  await main.getByRole('button', { name: 'Workflow', exact: true }).click()
  await main.getByLabel('Prepare this workflow after a matching merge').check()
  await main.getByLabel('Continue with another workflow').check()
  await main.getByRole('button', { name: 'Save draft' }).click()
  await expect(main.getByText('Draft saved.')).toBeVisible()
  const savedDraft = state.workflows.find((item) => item.draft['name'] === 'Major feature follow-up')!.draft
  expect((savedDraft['steps'] as Record<string, unknown>[])[1]!['needs']).toEqual(['compile'])
  expect(savedDraft['follow_on']).toMatchObject({ workflow_version_id: 'workflow-seed-v1', when: 'success' })
  await main.getByRole('button', { name: 'Publish version' }).click()
  await expect(main.getByText(/Version 1 published/)).toBeVisible()
  await main.getByRole('button', { name: 'Simulate' }).click()
  await expect(main.getByText('Simulation passed with warnings')).toBeVisible()
  await expect(main.getByText(/No side effects occurred/)).toBeVisible()
  await main.getByRole('button', { name: 'Attach to repository' }).click()
  await expect(main.getByText(/attached as a draft/)).toBeVisible()
  await expect(main.getByText('Repository attachment')).toBeVisible()
  await main.getByLabel('Exact source revision').fill('1'.repeat(40))
  await main.getByRole('button', { name: 'Review setup' }).click()
  const blockedSetup = main.getByRole('alert').filter({ hasText: 'Setup is blocked' })
  await expect(blockedSetup).toBeVisible()
  await expect(blockedSetup.getByText('operator_profile', { exact: true })).toBeVisible()
  await expect(main.getByRole('button', { name: 'Download setup bundle' })).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true)
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: testInfo.outputPath('workflow-library-desktop.png') })

  await main.getByRole('button', { name: 'Workflow library' }).click()
  await page.reload()
  await main.getByRole('button', { name: /Major feature follow-up/ }).first().click()
  await expect(main.getByText('This attachment cannot be installed.')).toBeVisible()
  await expect(main.locator('.wl-diagnostics').getByText('operator_profile', { exact: true })).toBeVisible()
  await expect(main.getByText(/pipeline install/)).toHaveCount(0)
  await main.getByRole('button', { name: 'Workflow library' }).click()
  const seed = main.getByRole('listitem').filter({ hasText: 'Release evidence' })
  await seed.getByRole('button', { name: 'Archive' }).click()
  await main.getByRole('button', { name: /Major feature follow-up/ }).first().click()
  const retainedReferences = main.getByRole('option', { name: /Release evidence v1 · archived reference \(retained\)/ })
  await expect(retainedReferences).toHaveCount(2)
  await expect(main.getByText(/immutable reference is retained/)).toHaveCount(2)
  await main.getByRole('button', { name: 'Workflow library' }).click()
  const original = main.getByRole('listitem').filter({ hasText: 'Major feature follow-up' }).first()
  await original.getByRole('button', { name: 'Duplicate' }).click()
  await expect(main.getByLabel('Name')).toHaveValue('Major feature follow-up copy')
  await main.getByRole('button', { name: 'Workflow library' }).click()
  const duplicate = main.getByRole('listitem').filter({ hasText: 'Major feature follow-up copy' })
  await duplicate.getByRole('button', { name: 'Delete draft' }).click()
  await expect(main.getByText('Major feature follow-up copy')).toHaveCount(0)
  await original.getByRole('button', { name: 'Archive' }).click()
  await expect(main.getByText('Major feature follow-up', { exact: true })).toHaveCount(0)
})

test('keeps the saved generation after publication fails and retries without another save', async ({ page }) => {
  const state = await installWorkflowLibraryMock(page)
  state.skills.push({ id: 'skill-retry', name: 'Release action', version: 1, generation: 1, digest: 'c'.repeat(64), entrypoint: 'SKILL.md', files: [], provenance: { kind: 'markdown', locator: 'pasted' }, created_at: 1_798_000_000, archived: false })
  state.workflows.push({ draft: { id: 'workflow-retry', name: 'Retry publication', summary: 'Original purpose', generation: 1, steps: [{ id: 'release', label: 'Release', needs: [], required: true, kind: 'action', skill_version_id: 'skill-retry', resource: 'release.json' }], trigger: null, follow_on: null, updated_at: 1_798_000_000, archived: false }, versions: [] })
  state.failNextPublish = true
  await page.addInitScript((token) => localStorage.setItem('agentscm.token', token), LOCAL_TOKEN)
  await page.goto('/#templates?view=workflows')
  const main = page.locator('#main')
  await main.getByRole('button', { name: /Retry publication/ }).click()
  await main.getByLabel('Purpose').fill('Saved before publication')
  await main.getByRole('button', { name: 'Publish version' }).click()
  await expect(main.getByText('Draft saved, but no version was published.')).toBeVisible()
  await expect(main.getByText('not found: skill resource missing.json')).toBeVisible()
  expect(state.updates).toHaveLength(1)
  expect(state.workflows[0]!.draft['generation']).toBe(2)
  await main.getByRole('button', { name: 'Publish version' }).click()
  await expect(main.getByText(/Version 1 published/)).toBeVisible()
  expect(state.updates).toHaveLength(1)
  expect(state.workflows[0]!.versions).toHaveLength(1)
})

